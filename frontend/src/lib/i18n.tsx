export function tOf(lang: Lang): Dict {
  return lang === "en" ? en : zh;
}

const LANG_KEY = "bidqa.lang";

export function readLang(): Lang {
  try {
    return localStorage.getItem(LANG_KEY) === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

export function saveLang(lang: Lang) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* 隐私模式等场景静默 */
  }
}

export type I18n = { lang: Lang; t: Dict; setLang: (l: Lang) => void };

export const LangCtx = createContext<I18n>({ lang: "zh", t: zh, setLang: () => {} });

export function useI18n(): I18n {
  return useContext(LangCtx);
}

/** 后端 status 段名（中文）→ 当前语言文案；未知段名原样展示。 */
export function stageText(stage: string, t: Dict): string {
  const map: Record<string, string> = {
    分析中: t.stageAnalyzing,
    取数中: t.stageFetching,
    向您确认: t.stageClarify,
    深度思考: t.stageThinking,
    生成中: t.stageGenerating,
    重新整理: t.stageRewriting,
    降级直答: t.stageDegrade,
  };
  return map[stage] ?? stage;
}
